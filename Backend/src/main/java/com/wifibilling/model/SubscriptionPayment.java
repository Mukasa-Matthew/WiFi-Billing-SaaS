package com.wifibilling.model;

import jakarta.persistence.*;
import lombok.*;
import java.time.OffsetDateTime;

/**
 * A verified subscription payment recorded by a Super Administrator.
 * recordRef is a server-generated unique idempotency key — a retried POST can
 * never create a second record. Revenue is computed from these rows only;
 * unpaid invoices are never counted as income.
 */
@Entity
@Table(name = "subscription_payments", indexes = {
        @Index(columnList = "tenant_id,paid_at"),
        @Index(columnList = "invoice_id")
})
@Getter @Setter @NoArgsConstructor @AllArgsConstructor @Builder
public class SubscriptionPayment {

    @Id @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "subscription_id", nullable = false)
    private Subscription subscription;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "invoice_id", nullable = false)
    private SubscriptionInvoice invoice;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "tenant_id", nullable = false)
    private Tenant tenant;

    @Column(nullable = false)
    private Long amount;

    @Column(nullable = false)
    private OffsetDateTime paidAt;

    @Column(nullable = false, length = 32)
    @Builder.Default
    private String method = "CASH";

    /** Optional external reference (e.g. MoMo transaction id) — unique when present. */
    @Column(length = 128, unique = true)
    private String externalRef;

    /** Idempotency key generated by the server per recorded payment. */
    @Column(nullable = false, unique = true, length = 64)
    private String recordRef;

    /** Super-admin account that recorded the payment. */
    private Long recordedBy;

    @Column(length = 255)
    private String note;

    @Column(name = "created_at")
    @Builder.Default
    private OffsetDateTime createdAt = OffsetDateTime.now();
}
