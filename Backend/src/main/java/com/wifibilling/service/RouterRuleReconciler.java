package com.wifibilling.service;

import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.boot.context.event.ApplicationReadyEvent;
import org.springframework.context.event.EventListener;
import org.springframework.stereotype.Component;

/** On every start (each deploy), queues corrected school-filter and tethering rules for routers that need them. */
@Slf4j
@Component
@RequiredArgsConstructor
public class RouterRuleReconciler {
    private final RouterManagementService management;

    @EventListener(ApplicationReadyEvent.class)
    public void reconcile() {
        try {
            int queued = management.resyncChangedRules();
            if (queued > 0) log.info("Queued {} router rule updates generated by this release", queued);
        } catch (RuntimeException e) {
            log.warn("Router rule reconciliation skipped: {}", e.getMessage());
        }
    }
}
