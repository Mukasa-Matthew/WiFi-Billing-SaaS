-- 4. Idempotent one-time launch trial initialization for existing non-superadmin tenants
-- Sets 7 full calendar days from the moment of activation (NOW() -> NOW() + 7 days).
-- Preserves historical paid, suspended, or cancelled records and flags ambiguous cases for Super Admin review.
DO $$
DECLARE
    r RECORD;
    v_default_plan_id BIGINT;
    v_default_fee BIGINT;
    v_now TIMESTAMP WITH TIME ZONE := NOW();
    v_trial_end TIMESTAMP WITH TIME ZONE := NOW() + INTERVAL '7 days';
    v_grace_end TIMESTAMP WITH TIME ZONE := NOW() + INTERVAL '9 days';
BEGIN
    SELECT id, price INTO v_default_plan_id, v_default_fee 
    FROM subscription_plans 
    WHERE active = TRUE 
    ORDER BY display_order ASC 
    LIMIT 1;

    IF v_default_fee IS NULL THEN
        v_default_fee := 50000;
    END IF;

    -- Only grant launch trial to tenants who DO NOT have any historical subscription records
    FOR r IN 
        SELECT t.id, t.name FROM tenants t 
        WHERE t.role <> 'ROLE_SUPERADMIN'
          AND NOT EXISTS (SELECT 1 FROM subscriptions s WHERE s.tenant_id = t.id)
    LOOP
        INSERT INTO subscriptions (
            tenant_id,
            plan_id,
            monthly_fee,
            anchor_day,
            start_date,
            next_renewal_date,
            expires_at,
            trial_starts_at,
            trial_ends_at,
            grace_until,
            trial_granted,
            status,
            admin_note,
            created_at,
            updated_at
        ) VALUES (
            r.id,
            v_default_plan_id,
            v_default_fee,
            EXTRACT(DAY FROM v_trial_end)::INT,
            v_now::DATE,
            v_trial_end::DATE,
            v_trial_end,
            v_now,
            v_trial_end,
            v_grace_end,
            TRUE,
            'TRIALING',
            'One-time 7-day launch trial activated at feature release.',
            v_now,
            v_now
        );
        RAISE NOTICE 'Granted one-time 7-day launch trial to tenant % (ID %)', r.name, r.id;
    END LOOP;

    -- Preserve historical records and flag ambiguous cases (e.g. historical paid/cancelled/suspended) for Super Admin review
    UPDATE subscriptions
    SET admin_note = COALESCE(admin_note, '') || ' [FLAGGED: Historical subscription record preserved for Super Admin review - no automatic trial granted]'
    WHERE status IN ('CANCELLED', 'SUSPENDED', 'EXPIRED', 'PAID')
      AND (trial_granted IS FALSE OR trial_granted IS NULL)
      AND (admin_note IS NULL OR admin_note NOT LIKE '%FLAGGED%');
END $$;

-- 5. Create subscription_notifications table for persistent, idempotent in-app & email reminders
CREATE TABLE IF NOT EXISTS subscription_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT NOT NULL REFERENCES subscriptions(id) ON DELETE CASCADE,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    notification_type VARCHAR(40) NOT NULL,
    billing_cycle_key VARCHAR(64) NOT NULL,
    title VARCHAR(160) NOT NULL,
    message TEXT,
    severity VARCHAR(20) DEFAULT 'INFO',
    email_sent BOOLEAN NOT NULL DEFAULT FALSE,
    dismissed BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL,
    CONSTRAINT uq_sub_notif_cycle UNIQUE (subscription_id, notification_type, billing_cycle_key)
);

CREATE INDEX IF NOT EXISTS idx_sub_notif_tenant ON subscription_notifications(tenant_id);
CREATE INDEX IF NOT EXISTS idx_sub_notif_dismissed ON subscription_notifications(tenant_id, dismissed);

-- 6. Create subscription_period_history table for immutable tenant subscription period tracking
CREATE TABLE IF NOT EXISTS subscription_period_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    subscription_id BIGINT NOT NULL REFERENCES subscriptions(id) ON DELETE CASCADE,
    plan_name VARCHAR(80) NOT NULL,
    period_type VARCHAR(32) NOT NULL,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    duration_days INT NOT NULL,
    amount_charged BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    payment_date TIMESTAMP WITH TIME ZONE,
    payment_reference VARCHAR(64),
    note VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_sub_hist_tenant ON subscription_period_history(tenant_id);
CREATE INDEX IF NOT EXISTS idx_sub_hist_start ON subscription_period_history(period_start);
